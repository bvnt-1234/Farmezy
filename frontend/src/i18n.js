/**
 * Main translation lookup function.
 * Matches by translation key, phrase, crop name, category, status, or unit.
 */
export function t(key, lang = "English") {
  if (!key || typeof key !== "string") return key;
  if (!lang || lang === "English") return key;

  const dict = translations[lang];
  if (dict && dict[key]) return dict[key];

  const trimmed = key.trim();
  if (dict && dict[trimmed]) return dict[trimmed];

  // Try lowercased / key-normalized
  const cleanKey = trimmed.toLowerCase().replace(/[^a-z0-9]/g, "");
  for (const [k, v] of Object.entries(dict || {})) {
    if (k.toLowerCase().replace(/[^a-z0-9]/g, "") === cleanKey) {
      return v;
    }
  }

  // Check Crop names
  if (CROP_TRANSLATIONS[trimmed] && CROP_TRANSLATIONS[trimmed][lang]) {
    return CROP_TRANSLATIONS[trimmed][lang];
  }
  for (const [cropEn, map] of Object.entries(CROP_TRANSLATIONS)) {
    if (cropEn.toLowerCase() === trimmed.toLowerCase()) {
      return map[lang] || key;
    }
  }

  // Check Categories
  if (CATEGORY_TRANSLATIONS[trimmed] && CATEGORY_TRANSLATIONS[trimmed][lang]) {
    return CATEGORY_TRANSLATIONS[trimmed][lang];
  }

  // Check Statuses
  if (STATUS_TRANSLATIONS[trimmed] && STATUS_TRANSLATIONS[trimmed][lang]) {
    return STATUS_TRANSLATIONS[trimmed][lang];
  }

  // Check Units
  if (UNIT_TRANSLATIONS[trimmed] && UNIT_TRANSLATIONS[trimmed][lang]) {
    return UNIT_TRANSLATIONS[trimmed][lang];
  }

  // Fallback to English dictionary or key
  return translations.English[key] || translations.English[trimmed] || key;
}

export function translateCrop(crop, lang) {
  if (!crop || lang === "English") return crop;
  return CROP_TRANSLATIONS[crop]?.[lang] || t(crop, lang);
}

export function translateCategory(cat, lang) {
  if (!cat || lang === "English") return cat;
  return CATEGORY_TRANSLATIONS[cat]?.[lang] || t(cat, lang);
}

export function translateStatus(status, lang) {
  if (!status || lang === "English") return status;
  return STATUS_TRANSLATIONS[status]?.[lang] || t(status, lang);
}

export function translateUnit(unit, lang) {
  if (!unit || lang === "English") return unit;
  return UNIT_TRANSLATIONS[unit]?.[lang] || t(unit, lang);
}

